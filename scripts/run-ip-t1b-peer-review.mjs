// scripts/run-ip-t1b-peer-review.mjs
//
// PA #IP-T1b — peer-reviews the single-file productDomains.js scrub via OpenRouter.
// Reads the staged diff (`git diff --cached`) and asks an independent model
// to confirm the leak is removed without consumer breakage. Writes a
// Markdown report to docs/peer-reviews/.
//
// ESM only. Node ≥ 18.

import { execFileSync } from 'node:child_process';
import { writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { peerReview } from './lib/peer-review.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');

function timestamp() {
  const d = new Date();
  const z = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${z(d.getMonth() + 1)}-${z(d.getDate())}_${z(d.getHours())}-${z(d.getMinutes())}-${z(d.getSeconds())}`;
}

function captureStagedDiff() {
  return execFileSync('git', ['diff', '--cached', '-U10'], {
    cwd: REPO, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024,
  });
}

function captureStagedNamesOnly() {
  return execFileSync('git', ['diff', '--cached', '--name-status'], {
    cwd: REPO, encoding: 'utf8', maxBuffer: 256 * 1024,
  });
}

const CRITERIA = `
You are an independent reviewer. The artifact below is the staged
\`git diff --cached\` for a single-file IP-hygiene scrub (PA #IP-T1b) on
\`api/_lib/productDomains.js\`.

Background:
- PA #IP-T1 (the prior commit) scrubbed \`.base44.app\` URLs from
  \`src/lib/veuProducts.js\` and \`/docs/*\`, and explicitly deferred the
  matching leak in \`api/_lib/productDomains.js\` to "Tier 1.b".
- This commit (Tier 1.b) is supposed to flip the MyBirthSafe entry's
  \`live_url\` from \`'https://safe-path.base44.app'\` to an empty string
  \`''\` — matching the existing pattern for ReachSMS / RelTwin which
  already have empty \`live_url\` fields.
- MyBirthSafe has no confirmed canonical .com domain yet; the dispatcher
  said do NOT invent one — use empty string when no canonical exists.

Review for:

A. CORRECTNESS — does the diff replace exactly the
   \`safe-path.base44.app\` URL with \`''\`, and nothing else?
B. SCOPE — was anything ELSE in productDomains.js touched (other product
   entries, helper functions, ORG block)? Anything else should be unchanged.
C. CONSUMER BREAKAGE — productDomains.js is imported by \`api/admin/seed.js\`
   and exported helpers like \`getCurrentLiveUrl\`. ReachSMS and RelTwin
   already had \`live_url: ''\`, so consumers must already tolerate empty
   strings. Is there any new breakage risk introduced by this specific
   change?
D. ESM ONLY — no \`require(\` or \`module.exports\` in the diff.
E. PLACEHOLDER TEXT — the dispatcher requires "no placeholder text;
   resolve completely." Empty string is acceptable per the dispatcher's
   explicit instruction. Comments noting the URL is TBD are acceptable.

Return ONLY a JSON object with this exact shape:
{
  "agreement_pct": <0-100 integer>,
  "scrub_status": "complete" | "incomplete" | "incorrect",
  "scrub_notes": "<string>",
  "scope_leakage": { "out_of_scope_modified": [<paths>] },
  "consumer_breakage_risks": [<strings>],
  "esm_violations": [<paths if any>],
  "additional_observations": [<strings>],
  "recommended_action": "approve" | "amend" | "block"
}

No prose. No markdown fences. Just the JSON.
`.trim();

function asMarkdown({ summary, names, agreement_pct, raw, model_used, degraded, latency_ms, total_ms }) {
  return `# PA #IP-T1b — IP Hygiene Tier 1.b Peer Review

**Generated:** ${new Date().toISOString()}
**Branch:** \`flowai-v0.1\`
**Reviewer model:** \`${model_used}\` ${degraded ? '(degraded — fallback used)' : '(primary)'}
**Latency:** ${latency_ms} ms inference / ${total_ms} ms total
**Agreement (auto-extracted):** ${agreement_pct === null ? '_unparseable_' : `**${agreement_pct}%**`}
**Acceptance gate:** ≥ 85%

---

## Files in the staged scrub diff

\`\`\`
${names.trim()}
\`\`\`

---

## Reviewer raw response

\`\`\`json
${raw.trim()}
\`\`\`

---

## Reviewer parsed findings

\`\`\`json
${JSON.stringify(summary, null, 2)}
\`\`\`

---

_Generated by \`scripts/run-ip-t1b-peer-review.mjs\` (ESM, OpenRouter via \`scripts/lib/peer-review.mjs\`)._
`;
}

async function main() {
  const outDir = path.join(REPO, 'docs', 'peer-reviews');
  if (!existsSync(outDir)) await mkdir(outDir, { recursive: true });
  const ts = timestamp();
  const outPath = path.join(outDir, `pa-ip-t1b-${ts}.md`);

  const diff = captureStagedDiff();
  const names = captureStagedNamesOnly();
  if (diff.trim().length === 0) {
    process.stderr.write('peer-review: nothing staged. Stage your scrub diff with `git add` first.\n');
    process.exit(2);
  }

  const t0 = Date.now();
  const result = await peerReview({
    artifact: diff,
    criteria: CRITERIA,
    model: 'openai/gpt-5',
  });
  const total_ms = Date.now() - t0;

  const md = asMarkdown({
    summary: result.findings,
    names,
    agreement_pct: result.agreement_pct,
    raw: result.raw,
    model_used: result.model_used,
    degraded: result.degraded,
    latency_ms: result.latency_ms,
    total_ms,
  });
  await writeFile(outPath, md, 'utf8');

  process.stdout.write(
    `model_used=${result.model_used} degraded=${result.degraded} ` +
    `latency_ms=${result.latency_ms} agreement_pct=${result.agreement_pct ?? 'null'} ` +
    `out=${path.relative(REPO, outPath)}\n`
  );
}

main().catch((e) => {
  process.stderr.write(`peer-review FAILED: ${e?.message ?? e}\n`);
  process.exit(1);
});
