import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const outputPath = resolve(__dirname, '../src/lib/observability/buildInfo.generated.js');
const checkOnly = process.argv.includes('--check');

function firstNonEmpty(...values) {
  for (const value of values) {
    if (typeof value === 'string' && value.trim()) return value.trim();
  }
  return null;
}

function git(args) {
  try {
    return execFileSync('git', args, {
      cwd: resolve(__dirname, '..'),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

function existingGeneratedFile() {
  try {
    return readFileSync(outputPath, 'utf8');
  } catch {
    return null;
  }
}

const commitFull = firstNonEmpty(
  process.env.VERCEL_GIT_COMMIT_SHA,
  process.env.VITE_VERCEL_GIT_COMMIT_SHA,
  process.env.VITE_GIT_COMMIT_SHA,
  process.env.GIT_COMMIT_SHA,
  process.env.COMMIT_SHA,
  process.env.FLOWAI_EXPECTED_HEAD,
  process.env.EXPECTED_HEAD,
  git(['rev-parse', 'HEAD']),
);

const branch = firstNonEmpty(
  process.env.VERCEL_GIT_COMMIT_REF,
  process.env.VERCEL_GIT_COMMIT_BRANCH,
  process.env.VITE_VERCEL_GIT_COMMIT_REF,
  process.env.VITE_GIT_BRANCH,
  process.env.GIT_BRANCH,
  process.env.BRANCH,
  git(['branch', '--show-current']),
);

if (!commitFull) {
  const existing = existingGeneratedFile();
  if (existing) {
    console.warn('[build-info] No commit source available; preserving existing generated build info.');
    process.exit(0);
  }
  console.warn('[build-info] No commit source available; writing unavailable build info.');
}

const escaped = (value) => JSON.stringify(value ?? null);
const content = `// Generated by scripts/write-build-info.mjs.
// Fallback identity for local-source Vercel CLI deployments where
// VERCEL_GIT_COMMIT_SHA is not available at runtime.

export const BUILD_INFO = Object.freeze({
  commitFull: ${escaped(commitFull)},
  branch: ${escaped(branch)},
  source: ${escaped(commitFull ? 'git-or-env' : 'unavailable')},
  generatedAt: ${escaped(new Date().toISOString())},
});
`;

if (checkOnly) {
  console.log(`[build-info] Check ${commitFull ? commitFull.slice(0, 12) : 'unavailable'}; generated file not written.`);
  process.exit(0);
}

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, content);
console.log(`[build-info] Wrote ${commitFull ? commitFull.slice(0, 12) : 'unavailable'} to ${outputPath}`);
