  '_test',
  'system',
  jsonb_build_object(
    'is_system_test_tenant', true,
    'product_scope',         '_test',
    'created_by_migration',  '0012_test_tenant.sql',
    'never_bind_to_customer', true
  )
)
on conflict (clerk_org_id) do nothing;

