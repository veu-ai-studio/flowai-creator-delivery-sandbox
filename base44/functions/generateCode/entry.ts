function sanitizeRaw(raw) {
  if (!raw) return '';
  let cleaned = raw.replace(/```[a-z]*\n?/gi, '').replace(/```/g, '');
  const start = cleaned.indexOf('{');
  const end = cleaned.lastIndexOf('}');
  if (start !== -1 && end !== -1 && end > start) {
    cleaned = cleaned.slice(start, end + 1);
  }
  return cleaned.trim();
}

function validate(parsed) {
  if (!parsed || !Array.isArray(parsed.files) || parsed.files.length === 0) {
    return { valid: false, reason: 'Missing or empty files array' };
  }
  for (const file of parsed.files) {
    if (typeof file.path !== 'string' || !file.path.trim()) {
      return { valid: false, reason: `File entry has invalid path: ${JSON.stringify(file).slice(0, 80)}` };
    }
    if (typeof file.content !== 'string' || file.content.trim().length < 10) {
      return { valid: false, reason: `File "${file.path}" has empty or too-short content` };
    }
  }
  const paths = parsed.files.map(f => f.path);
  const missing = REQUIRED_PATHS.filter(r => !paths.includes(r));
  if (missing.length > 0) {
    return { valid: false, reason: `Missing required files: ${missing.join(', ')}` };
  }

  const html = parsed.files.find(f => f.path === 'frontend/index.html');
  if (html && !html.content.includes('<html')) {
    return { valid: false, reason: 'frontend/index.html does not contain valid HTML' };
  }

  const api = parsed.files.find(f => f.path === 'backend/api.js');
  if (api) {
    if (!api.content.includes('express')) {
      return { valid: false, reason: 'backend/api.js does not use express' };
    }
    if (!api.content.includes('/api/run')) {
      return { valid: false, reason: 'backend/api.js missing POST /api/run route' };
    }
    if (!api.content.includes('module.exports')) {
      return { valid: false, reason: 'backend/api.js missing module.exports = app' };
    }
  }

  const pkg = parsed.files.find(f => f.path === 'package.json');
  if (pkg) {
    try {
      const p = JSON.parse(pkg.content);
      if (!p.scripts || !p.scripts.start) {
        return { valid: false, reason: 'package.json missing scripts.start' };
      }
    } catch {
      return { valid: false, reason: 'package.json is not valid JSON' };
    }
  }

  return { valid: true, reason: 'OK' };
}

async function callOpenAI(apiKey, systemPrompt, userPrompt) {
  const res = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model: 'gpt-4o',
      messages: [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: userPrompt },
      ],
      temperature: 0.2,
      max_tokens: 14000,
      response_format: { type: 'json_object' },
    }),
  });

  if (!res.ok) {
    const err = await res.json();
    throw new Error(`OpenAI API error ${res.status}: ${JSON.stringify(err)}`);
  }

  const data = await res.json();
  const raw = data.choices?.[0]?.message?.content || '';
  console.log('[generateCode] raw output (first 300 chars):', raw.slice(0, 300));

  const sanitized = sanitizeRaw(raw);
  let parsed;
  try {
    parsed = JSON.parse(sanitized);
  } catch (e) {
    throw new Error(`JSON parse failed: ${e.message}. Snippet: ${sanitized.slice(0, 200)}`);
  }

  console.log('[generateCode] file count:', parsed?.files?.length ?? 'N/A');
  return { parsed, tokens: data.usage?.total_tokens || 0 };
}

