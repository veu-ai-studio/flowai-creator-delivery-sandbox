export const BUILD_EXECUTION_WORKER_MODULE = 'api/_lib/buildExecutionWorker.js';
export const BUILD_EXECUTION_WORKER_ENTRY_POINT = '/api/forge/build';
export const BUILD_EXECUTION_WORKER_WORKFLOW_FILE_NAME = 'flowai-build-execution-worker-stage1.yml';
export const BUILD_EXECUTION_WORKER_WORKFLOW_PATH = `.github/workflows/${BUILD_EXECUTION_WORKER_WORKFLOW_FILE_NAME}`;
export const BUILD_EXECUTION_WORKER_WORKFLOW_IDENTIFIER = BUILD_EXECUTION_WORKER_WORKFLOW_FILE_NAME;

const GITHUB_API_BASE = 'https://api.github.com';
const DEFAULT_POLL_INTERVAL_MS = 4_000;
const DEFAULT_MAX_POLL_ATTEMPTS = 60;
const SAFE_PROOF_ID = /^[a-zA-Z0-9._-]+$/;

export class BuildExecutionWorkerError extends Error {
  constructor(message, { status = 500, code = 'BUILD_EXECUTION_WORKER_ERROR', details = null } = {}) {
    super(message);
    this.name = 'BuildExecutionWorkerError';
    this.status = status;
    this.code = code;
    this.details = details;
  }
}

export function createBuildRequestId(now = new Date(), idFactory = randomUUID) {
  const stamp = now.toISOString().replace(/[-:.]/g, '').slice(0, 15);
  return `flowai-build-request-${stamp}-${idFactory().slice(0, 8)}`;
}

export function createBuildProofRunId(now = new Date(), idFactory = randomUUID) {
  const stamp = now.toISOString().replace(/[-:.]/g, '').slice(0, 15);
  return `flowai-build-${stamp}-${idFactory().slice(0, 8)}`;
}

export function resolveFlowAiBuildCommit(env = process.env) {
  return (
    env.VERCEL_GIT_COMMIT_SHA
    || env.FLOWAI_EXPECTED_HEAD
    || env.GIT_COMMIT
    || env.GIT_BRANCH
    || 'unknown'
  );
}

export function resolveBuildExecutionSandbox(env = process.env) {
  const owner = (env.FLOWAI_BUILD_EXECUTION_SANDBOX_OWNER || APPROVED_SANDBOX_OWNER).trim();
  const repo = (env.FLOWAI_BUILD_EXECUTION_SANDBOX_REPO || APPROVED_SANDBOX_REPO).trim();
  return {
    owner,
    repo,
    fullName: `${owner}/${repo}`,
    approved: owner === APPROVED_SANDBOX_OWNER && repo === APPROVED_SANDBOX_REPO,
  };
}

export function assertApprovedBuildExecutionSandbox(config) {
  if (!config?.approved) {
    throw new BuildExecutionWorkerError('BuildExecutionWorker target is not the approved sandbox repository.', {
      status: 409,
      code: 'SANDBOX_BOUNDARY_STOP',
      details: {
        requestedSandbox: config?.fullName || null,
        approvedSandbox: `${APPROVED_SANDBOX_OWNER}/${APPROVED_SANDBOX_REPO}`,
      },
    });
  }
}

export function mutatedFilePathForProofRun(proofRunId) {
  assertSafeProofRunId(proofRunId);
  return `proof/build-execution/${proofRunId}.json`;
}

