export default function CapabilityTransfer() {
  const navigate = useNavigate();
  const [selected, setSelected] = useState(null);
  const [targetUrl, setTargetUrl] = useState('');
  const [generating, setGenerating] = useState(false);
  const [generatedSprint, setGeneratedSprint] = useState(null);

  const generate = async () => {
    if (!selected || !targetUrl.trim()) return;
    setGenerating(true);
    setGeneratedSprint(null);
    // Simulate AI generation (sprint is template-based)
    await new Promise(r => setTimeout(r, 800));
    const sprint = buildConsolidatedSprint(selected, targetUrl.trim());
    setGeneratedSprint(sprint);
    setGenerating(false);
  };

  return (
    <div className="p-8 lg:p-10 max-w-4xl space-y-6">
      <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }}>
        <h1 className="text-3xl font-bold tracking-tight text-foreground flex items-center gap-2">
          <Package className="h-7 w-7 text-primary" /> Capability Transfer
        </h1>
        <p className="text-sm text-muted-foreground mt-1">
          Install FlowAI governance capabilities into any Base44 product with a single consolidated sprint.
        </p>
      </motion.div>

      {/* Capability selection */}
      <div className="space-y-3">
        <p className="text-[11px] font-bold text-muted-foreground uppercase tracking-wide">Step 1 — Select Capability</p>
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
          {CAPABILITIES.map(cap => {
            const Icon = cap.icon;
            const isSelected = selected === cap.id;
            return (
              <div
                key={cap.id}
                onClick={() => { setSelected(cap.id); setGeneratedSprint(null); }}
                className={`rounded-xl border p-5 cursor-pointer transition-all space-y-3 ${isSelected ? cap.color + ' ring-1' : 'border-border bg-card hover:border-primary/30'}`}
              >
                <div className="flex items-center gap-2">
                  <Icon className={`h-4 w-4 ${isSelected ? '' : 'text-muted-foreground'}`} />
                  <span className="text-sm font-bold">{cap.label}</span>
                  {isSelected && <span className="ml-auto text-[10px] font-bold bg-primary/20 text-primary px-2 py-0.5 rounded-full">SELECTED</span>}
                </div>
                <p className="text-[11px] text-muted-foreground">{cap.desc}</p>
                <ul className="space-y-1">
                  {cap.components.map(c => (
                    <li key={c} className="text-[10px] text-muted-foreground flex items-center gap-1.5">
                      <span className="h-1 w-1 rounded-full bg-muted-foreground/50 shrink-0" /> {c}
                    </li>
                  ))}
                </ul>
                <div className="flex gap-2 flex-wrap pt-1">
                  <button
                    onClick={e => { e.stopPropagation(); navigate(cap.detailPath); }}
                    className="text-[10px] text-primary hover:text-primary/80 underline underline-offset-2"
                  >
                    View Package →
                  </button>
                  <button
                    onClick={e => { e.stopPropagation(); navigate(cap.installPath); }}
                    className="text-[10px] text-muted-foreground hover:text-foreground underline underline-offset-2"
                  >
                    View All Product Sprints →
                  </button>
                </div>
              </div>
            );
          })}
        </div>
      </div>

      {/* Target URL */}
      <div className="space-y-3">
        <p className="text-[11px] font-bold text-muted-foreground uppercase tracking-wide">Step 2 — Target Product URL</p>
        <div className="flex gap-2">
          <Input
            value={targetUrl}
            onChange={e => setTargetUrl(e.target.value)}
            placeholder="https://saigedemo.com"
            className="h-9 text-sm flex-1"
          />
          <Button onClick={generate} disabled={!selected || !targetUrl.trim() || generating} className="gap-1.5 shrink-0">
            {generating ? <Loader2 className="h-4 w-4 animate-spin" /> : <Zap className="h-4 w-4" />}
            Generate Sprint
          </Button>
        </div>
      </div>

      {/* Generated sprint */}
      <AnimatePresence>
        {generatedSprint && (
          <motion.div
            initial={{ opacity: 0, y: 8 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0 }}
            className="rounded-xl border border-emerald-500/30 bg-emerald-500/5 p-5 space-y-3"
          >
            <div className="flex items-center justify-between gap-3 flex-wrap">
              <p className="text-sm font-bold text-emerald-400">Sprint Generated</p>
              <CopyBtn text={generatedSprint} />
            </div>
            <p className="text-xs text-muted-foreground">
              Copy this sprint and paste it into the target product's Base44 project. All components will be installed in a single operation.
            </p>
            <div className="rounded-lg bg-background border border-border p-4">
              <pre className="text-[11px] text-foreground whitespace-pre-wrap font-mono leading-relaxed overflow-x-auto max-h-64 overflow-y-auto">
                {generatedSprint}
              </pre>
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}